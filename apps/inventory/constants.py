from decimal import Decimal

# ────────────────────────────────────────────────────────────────────────
# ТИПЫ ДВИЖЕНИЙ СКЛАДА (StockMovement.kind)
# ────────────────────────────────────────────────────────────────────────
# Каждый тип движения имеет строгую семантику:
#
# IN        — поступление от поставщика (приёмка)
# OUT       — списание при доставке (физическое списание)
# RESERVE   — резерв под подтверждённый заказ (заморозка)
# RELEASE   — освобождение резерва (отмена заказа / истечение TTL)
# ADJUSTMENT— ручная корректировка (инвентаризация, брак, опечатка)
#
# НАПРАВЛЕНИЕ ДВИЖЕНИЯ:
#   IN, RELEASE   → увеличивают available_quantity
#   OUT, RESERVE  → уменьшают available_quantity
#   ADJUSTMENT    → может быть в любую сторону (+/-)

# ────────────────────────────────────────────────────────────────────────
# ЛИМИТЫ
# ────────────────────────────────────────────────────────────────────────

# Порог сигнализации «мало товара» (low stock).
# Если Stock.quantity ≤ LOW_STOCK_THRESHOLD → нужен заказ поставщику.
# Используется в management command check_low_stock.
LOW_STOCK_THRESHOLD = 5

# Максимальная длина примечания к движению склада.
MAX_MOVEMENT_NOTE_LENGTH = 500

# Максимальное количество позиции заказа для одной операции резервирования.
# Защита от аномальных запросов.
MAX_RESERVE_ITEMS = 200

# ────────────────────────────────────────────────────────────────────────
# Throttling
# ────────────────────────────────────────────────────────────────────────
INVENTORY_USER_THROTTLE_RATE = '60/min'

# ────────────────────────────────────────────────────────────────────────
# Период очистки старых движений (для management command)
# ────────────────────────────────────────────────────────────────────────
# Движения старше MOVEMENT_RETENTION_DAYS дней можно архивировать/удалять.
# 365 дней = 1 год (аудит за последний год всегда доступен).
MOVEMENT_RETENTION_DAYS = 365
