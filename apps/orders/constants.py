from decimal import Decimal

# ────────────────────────────────────────────────────────────────────────
# ЛИМИТЫ ЗАКАЗА
# ────────────────────────────────────────────────────────────────────────

# Максимальное количество РАЗНЫХ позиций (variant) в одном заказе.
#
# ПОЧЕМУ 200, А НЕ ∞:
#   1) Защита от аномальных заказов: 10 000 позиций → огромный OrderItem-объём
#      → медленная сериализация → таймаут API.
#   2) Реальный B2B-заказ: обычно 10-30 позиций. 200 — щедрый запас.
#   3) При 200+ позициях стоит предложить разбиение на несколько заказов.
#
# 📖 https://cheatsheetseries.owasp.org/cheatsheets/Denial_of_Service_Cheat_Sheet.html
MAX_ORDER_ITEMS = 200

# Максимальное количество единиц ОДНОЙ позиции в заказе.
# POST /api/v1/orders/ с quantity=999999 → отклоняется.
#
# ПОЧЕМУ 999:
#   • Трёхзначное число — удобный upper bound
#   • Для B2B 999 штук одного SKU достаточно
#   • Совпадает с MAX_ITEM_QUANTITY в корзине
MAX_ITEM_QUANTITY = 999

# Минимальная сумма заказа для оформления.
# Если total < MIN_ORDER_TOTAL → заказ отклоняется.
#
# ПОЧЕМУ НЕ 0:
#   • Оформление заказа стоит денег (интеграция с платёжкой, склад, логистика)
#   • Заказ на 0.01₽ → операционные расходы > выручка
#   • Защита от «тестовых» заказов ботами
#
# Decimal('1.00') — 1 рубль. Увеличите при необходимости.
# 📖 https://docs.python.org/3/library/decimal.html
MIN_ORDER_TOTAL = Decimal('1.00')

# Максимальная сумма заказа.
# Decimal('99_999_999.99') — ~$1M, достаточно для любого реального заказа.
#
# ПОЧЕМУ НУЖЕН:
#   Защита от опечаток: пользователь ввёл 999999999999₽ вместо 9999₽.
#   Платёжные системы тоже имеют лимиты — синхронизируем с ними.
MAX_ORDER_TOTAL = Decimal('99_999_999.99')

# ────────────────────────────────────────────────────────────────────────
# ПРЕФИКС НОМЕРА ЗАКАЗА
# ────────────────────────────────────────────────────────────────────────

# Префикс номера заказа: ORD-{6 цифр} → ORD-000001, ORD-000123
#
# ПОЧЕМУ НЕ ПРОСТО id (1, 2, 3...):
#   1) Безопасность: порядковый номер раскрывает количество заказов
#      (конкуренты узнают ваш объём)
#   2) UX: «Ваш заказ ORD-000123» звучит профессиональнее чем «заказ 123»
#   3) Масштабируемость: при нескольких магазинах — разные префиксы
#      (ORD, WHL, SPL) → различать источник
#
# Длина номера: ORDER_NUMBER_PREFIX + '-' + 6 цифр = 10 символов
ORDER_NUMBER_PREFIX = 'ORD'

# Количество цифр в номере заказа (zero-padded).
# 6 цифр → до 999 999 заказов без изменения формата.
# При превышении: автоматическое удлинение (format с 06d → 7+ цифр).
ORDER_NUMBER_DIGITS = 6

# ────────────────────────────────────────────────────────────────────────
# СТАТУСЫ ЗАКАЗА (Finite State Machine)
# ────────────────────────────────────────────────────────────────────────

# Статусы заказа реализованы как TextChoices (Enum в Django).
# Используются ниже в models/order.py — OrderStatus.
#
# ЖИЗНЕННЫЙ ЦИКЛ (state machine):
#
#   PENDING → CONFIRMED → PROCESSING → SHIPPED → DELIVERED
#      ↓          ↓            ↓
#   CANCELLED  CANCELLED   CANCELLED
#
# Правила переходов валидируются в OrderService:
#   • Из CANCELLED нельзя перейти никуда
#   • Из DELIVERED нельзя перейти никуда
#   • Откат возможен только в особых случаях (REFUNDED)
#
# 📖 https://martinfowler.com/eaaCatalog/finiteStateMachine.html
# 📖 https://en.wikipedia.org/wiki/Order_status

# ────────────────────────────────────────────────────────────────────────
# TTL (Time-To-Live) — время жизни черновиков
# ────────────────────────────────────────────────────────────────────────

# Заказы в статусе PENDING, не обновлявшиеся дольше
# ORDER_PENDING_TTL_HOURS часов, автоматически отменяются
# командой: python manage.py cleanup_stale_orders
#
# ПОЧЕМУ 24 ЧАСА:
#   • < 1 часа — слишком агрессивно (пользователь может отвлечься)
#   • > 72 часов — «замороженный» сток (невозможно продать другим)
#   • 24 часа — золотая середина: достаточно для оплаты, не блокируем сток навсегда
#
# ВАЖНО: если используется резервирование стока (inventory),
# то при отмене зарезервированный сток должен быть освобождён.
ORDER_PENDING_TTL_HOURS = 24

# ────────────────────────────────────────────────────────────────────────
# Throttling — ограничение частоты запросов к API заказов
# ────────────────────────────────────────────────────────────────────────

# Лимит для АВТОРИЗОВАННЫХ пользователей.
# 30/min — оформить 30 заказов в минуту нереально для нормального пользователя.
# Но бот с украденным JWT-токеном может спамить → ограничиваем.
# 📖 https://www.django-rest-framework.org/api-guide/throttling/#userratethrottle
ORDER_USER_THROTTLE_RATE = '30/min'

