CANCELLATION_REASONS = (
    ('changed_mind', 'Передумал(а)'),
    ('found_cheaper', 'Нашёл(ла) дешевле'),
    ('delivery_too_long', 'Слишком долгая доставка'),
    ('wrong_item', 'Ошибка в заказе'),
    ('payment_failed', 'Не удалось оплатить'),
    ('other', 'Другая причина'),
)
