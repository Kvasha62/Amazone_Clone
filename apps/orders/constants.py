# ЧТО БУДЕТ, ЕСЛИ УДАЛИТЬ ФАЙЛ:
#   • ImportErrors везде: ORDER_NUMBER_PREFIX, MAX_ORDER_ITEMS, ...
#   • Модели не смогут создать CheckConstraint (MAX_ORDER_ITEMS)
#   • Сервисы не смогут валидировать лимиты
