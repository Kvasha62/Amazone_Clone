# ЛИМИТЫ РАЗМЕРА КОРЗИНЫ
# ────────────────────────────────────────────────────────────────────────

# Максимальное количество РАЗНЫХ позиций (variant) в одной корзине.
# Одна позиция = один вариант товара (SKU-A × 5 шт. = 1 позиция).
#
# ПОЧЕМУ 100, А НЕ ∞:
#   1) Защита от DoS: бот отправляет POST /cart/items/ 10 000 раз
#      → каждая позиция = строка в БД → таблица cart_cartitem растёт.
#      100 позиций → максимум 100 × 8 байт (FK) = 800 байт на корзину.
#   2) Сериализация: CartSerializer перебирает все items →
#      10 000 позиций = 10 000 запросов к variant/product → 30+ секунд.
#   3) UX: никто не кладёт 100+ товаров — если кладёт, что-то не так.
#
# 📖 https://cheatsheetseries.owasp.org/cheatsheets/Denial_of_Service_Cheat_Sheet.html
MAX_CART_ITEMS = 100

# Максимальное количество единиц ОДНОЙ позиции.
# Пользователь может заказать SKU-A × 999 штук, но не 1000.
#
# ПОЧЕМУ 999:
#   • Целое трёхзначное число — удобный上限 (upper bound)
#   • Даже для B2B-клиентов 999 штук одного SKU достаточно
#   • PostgreSQL PositiveIntegerField → 4 байта, но CHECK constraint
#     ограничивает до 999 → при bulk_insert нет превышения
#
# Используется в:
#   • CartItem.Meta.CheckConstraint (БД-уровень)
#   • AddToCartInputSerializer / UpdateCartItemInputSerializer (API-уровень)
#   • CartService.add_item() (сервисный уровень)
MAX_ITEM_QUANTITY = 999

# ────────────────────────────────────────────────────────────────────────
# TTL (Time-To-Live) — время жизни неактивных корзин
# ────────────────────────────────────────────────────────────────────────

# Корзины, неактивные дольше CART_INACTIVE_TTL_DAYS дней,
# БЕЗВОЗВРАТНО удаляются командой:
#   python manage.py cleanup_expired_carts
#
# ПОЧЕМУ 30 ДНЕЙ:
#   • < 7 дней — слишком агрессивно (пользователь вернётся через неделю)
#   • > 90 дней — таблица разрастается (миллионы старых корзин)
#   • 30 дней — золотая середина: + аналитика за месяц, − не храним мусор
#
# 📖 https://docs.djangoproject.com/en/stable/howto/custom-management-commands/
CART_INACTIVE_TTL_DAYS = 30

# Активные ГЕСТЕВЫЕ корзины, не обновлявшиеся дольше
# CART_GUEST_STALE_DAYS дней, помечаются неактивными при cleanup.
#
# ПОЧЕМУ 14 ДНЕЙ (а не 30):
#   Гостевые корзины = анонимные, без пользователя.
#   Вероятность возврата гостя через 2 недели → ~0%.
#   Смысл хранить активную гостевую корзину 30 дней нет.
#
# ПОЧЕМУ НЕ УДАЛЯЕМ СРАЗУ, А ДЕАКТИВИРУЕМ:
#   Сначала деактивируем → на следующей cleanup (через 30 дней) → удалим.
#   Двухфазная «мусорная корзина»: если что — можно восстановить.
CART_GUEST_STALE_DAYS = 14

# ────────────────────────────────────────────────────────────────────────
# Throttling — ограничение частоты запросов
# ────────────────────────────────────────────────────────────────────────

# Лимит запросов к эндпоинтам корзины для АНОНИМОВ (незарегистрированных).
# '30/min' = максимум 30 запросов в минуту с одного IP.
#
# ПОЧЕМУ ТАКАЯ СТРОГОСТЬ:
#   Анонимный бот может спамить POST /cart/items/
#   и создавать тысячи корзин → перегрузка БД.
#   30/min достаточно для нормального пользователя
#   (кликнуть «Добавить» 30 раз за минуту — нереально).
#
# Формат: 'count/period' где period = s (second), m (minute), h (hour), d (day)
# 📖 https://www.django-rest-framework.org/api-guide/throttling/#anoneratethrottle
CART_ANON_THROTTLE_RATE = '30/min'

# Лимит для АВТОРИЗОВАННЫХ пользователей.
# 120/min = 2 запроса в секунду — более мягкий, чем для анонимов.
# Авторизованный пользователь уже прошёл регистрацию → доверяем больше.
#
# Но всё равно ограничиваем: скомпрометированный JWT-токен
# может использоваться ботом → 120/min сдерживает ущерб.
# 📖 https://www.django-rest-framework.org/api-guide/throttling/#userratethrottle
CART_USER_THROTTLE_RATE = '120/min'
