# ==============================================================================
# apps/catalog/models/brand.py — Бренд товара
# ==============================================================================
# Бренд — справочник производителей (Nike, Samsung, Apple...).
# Используется для:
#   - Фильтрации каталога: ?brand=nike
#   - Страницы бренда: /brands/nike/
#   - select_related в listing-е (без N+1)
#
# Архитектурные решения:
#   - slug генерируется ОДИН раз при создании и НЕ меняется при переименовании.
#     Причина: SEO-ссылки /brands/nike/ не должны ломаться если бренд
#     переименовали в «Nike Inc.». Это стандарт Amazon/e-commerce.
#   - is_active позволяет скрыть бренд из каталога без удаления
#     (мягкое удаление — товары бренда сохраняются для аналитики).
# ==============================================================================

from django.db import models

# slug_service — утилита для генерации уникальных URL-friendly слагов.
# Подробно — см. apps.catalog.services.slug_service (будет создан).
from apps.catalog.services.slug_service import generate_unique_slug
# BaseModel — created_at, updated_at (подробно — см. apps/core/models/base_model.py)
from apps.core.models import BaseModel


class Brand(BaseModel):
    """
    Бренд товара.

    Slug генерируется автоматически в save() из name.
    После создания slug НЕ меняется — для стабильности URL.
    """

    # ------------------------------------------------------------------
    # name — название бренда
    # ------------------------------------------------------------------
    # unique=True → Django автоматически создаёт B-tree индекс.
    # Нам не нужен отдельный db_index=True — unique уже включает его.
    #
    # Почему max_length=100:
    #   Реальные названия брендов обычно < 50 символов.
    #   100 — с запасом для edge-cases вроде
    #   «The North Face» или «L'Oréal Paris».
    # ------------------------------------------------------------------
    name = models.CharField(
        'Название',
        max_length=100,
        unique=True,               # unique уже создаёт индекс
    )

    # ------------------------------------------------------------------
    # slug — URL-friendly идентификатор
    # ------------------------------------------------------------------
    # SlugField валидирует: только буквы, цифры, дефисы, подчёркивания.
    # unique=True — для URL /brands/<slug>/ нужен уникальный slug.
    # blank=True — разрешаем пустое при POST, save() заполнит автоматически.
    #
    # Почему НЕ editable=False:
    #   В admin менеджер может захотеть задать slug вручную
    #   (например, бренд с нестандартным названием).
    # ------------------------------------------------------------------
    slug = models.SlugField(
        'Слаг',
        max_length=255,
        unique=True,               # unique уже создаёт индекс
        blank=True,
    )

    # ------------------------------------------------------------------
    # description — описание бренда (для страницы бренда)
    # ------------------------------------------------------------------
    # blank=True — описание опционально (не все бренды его заполняют)
    # ------------------------------------------------------------------
    description = models.TextField(
        'Описание',
        blank=True,
    )

    # ------------------------------------------------------------------
    # logo — логотип бренда
    # ------------------------------------------------------------------
    # upload_to='brands/%Y/%m/' — файлы складываются в
    #   MEDIA_ROOT/brands/2024/06/ — по годам и месяцам.
    #   Предотвращает накопление тысяч файлов в одной директории
    #   (файловые системы медлеют при > 10K файлов в папке).
    #
    # null=True — в БД хранится NULL (не пустая строка).
    # blank=True — в форме/admin поле необязательное.
    # ------------------------------------------------------------------
    logo = models.ImageField(
        'Логотип',
        upload_to='brands/%Y/%m/',
        null=True,
        blank=True,
    )

    # ------------------------------------------------------------------
    # is_active — мягкое удаление
    # ------------------------------------------------------------------
    # db_index=True — потому что почти каждый запрос фильтрует
    #   Brand.objects.filter(is_active=True). Без индекса — Full Scan.
    # ------------------------------------------------------------------
    is_active = models.BooleanField(
        'Активен',
        default=True,
        db_index=True,
    )

    class Meta:
        verbose_name = 'Бренд'
        verbose_name_plural = 'Бренды'
        # Сортировка по алфавиту — логично для справочника брендов
        ordering = ('name',)

    def __str__(self) -> str:
        return self.name

    def get_absolute_url(self) -> str:
        """URL страницы бренда во фронтенде."""
        return f'/brands/{self.slug}/'

    def save(self, *args, **kwargs):
        # ------------------------------------------------------------------
        # Авто-генерация slug при первом сохранении.
        #
        # if not self.slug — slug генерируется ТОЛЬКО если он пустой.
        # При переименовании бренда slug НЕ меняется —
        # SEO-ссылки остаются стабильными.
        #
        # generate_unique_slug проверяет уникальность:
        #   если slug 'nike' уже занят → создаст 'nike-2', 'nike-3' и т.д.
        # ------------------------------------------------------------------
        if not self.slug:
            self.slug = generate_unique_slug(
                instance=self,
                field_value=self.name,
            )
        super().save(*args, **kwargs)
