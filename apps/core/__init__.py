# ==============================================================================
# apps/core/__init__.py
# ==============================================================================
# Пустой __init__.py делает директорию «core» Python-пакетом.
#
# Почему это нужно:
#   Без __init__.py Python не распознаёт директорию как пакет,
#   и `from apps.core.models import BaseModel` выбросит ImportError.
#   Это стандартный механизм Python-пакетов (regular package).
#
# Почему файл не пустой:
#   default_app_config указывает Django какой AppConfig использовать
#   при загрузке приложения. Это нужно для старых версий Django (< 3.2)
#   и для совместимости с INSTALLED_APPS вида 'apps.core'
#   (без суффикса .apps.CoreConfig).
# ==============================================================================

# Строка ниже говорит Django: «при загрузке apps.core используй
# класс CoreConfig из apps.core.apps». В новых версиях Django
# (3.2+) это необязательно — Django автоматически находит AppConfig
# по имени приложения, но оставляем для совместимости.
default_app_config = 'apps.core.apps.CoreConfig'
