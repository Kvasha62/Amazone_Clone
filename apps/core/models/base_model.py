# ==============================================================================
# apps/core/models/base_model.py — Абстрактная базовая модель
# ==============================================================================
# Все модели проекта наследуются от BaseModel (кроме User — он наследует
# AbstractUser). BaseModel предоставляет:
#   - created_at  — дата создания (автоматически, один раз)
#   - -updated_at  — дата последнего обновления (автоматически, каждый save)
#
# Паттерн «Abstract Base Model» — стандарт Django для DRY:
#   вместо того чтобы в каждой модели писать created_at/updated_at,
#   пишем один раз в BaseModel и наследуем.
#
# ВАЖНО: BaseModel НЕ содержит id/pk — Django автоматически добавляет
# поле id (тип определяется default_auto_field = BigAutoField).
# Если в модели нужно uuid — она добавляет его сама.
#
# ВАЖНО: BaseModel НЕ задаёт Meta.ordering — каждая конкретная модель
# должна определить ordering самостоятельно. Это осозненное решение:
#   1. Глобальный ordering замедляет запросы на больших таблицах.
#   2. Разным моделям нужен разный порядок.
#   3. Без ordering — Django выдаст UnorderedObjectListWarning,
#      что видно сразу (а не на проде).
# ==============================================================================

from django.db import models


class BaseModel(models.Model):
    """
    Абстрактная базовая модель проекта.

    Предоставляет:
      - created_at  — дата создания (автоматически)
      - updated_at  — дата последнего обновления (автоматически)

    Контракт для дочерних моделей:
      - Meta.ordering — ДОЛЖНА быть определена явно в каждой конкретной модели.
      - Meta.verbose_name / verbose_name_plural — рекомендуется задавать
        в каждой модели для читаемости в админке.
    """

    # --------------------------------------------------------------------------
    # created_at — когда была создана запись
    # --------------------------------------------------------------------------
    # auto_now_add=True означает:
    #   - При первом save() Django автоматически установит текущее время
    #   - При последующих save() поле НЕ меняется
    #
    # Зачем это нужно:
    #   - Сортировка «сначала новые» (ordering = ['-created_at'])
    #   - Фильтрация «за последний месяц»
    #   - Аналитика: «когда пользователь зарегистрировался»
    #
    # db_index=True:
    #   Создаёт B-tree индекс в PostgreSQL. Без индекса ORDER BY created_at
    #   будет Full Table Scan — на таблице с миллионами записей это секунды.
    #   С индексом — миллисекунды.
    #
    #   Индекс занимает место на диске (~10-20% от размера таблицы),
    #   но для created_at это оправдано — почти каждый listing-запрос
    #   сортирует по дате создания.
    #
    # verbose_name='Создано':
    #   Человекочитаемое название для Django admin.
    #   Отображается как заголовок столбца в списке записей.
    # --------------------------------------------------------------------------
    created_at = models.DateTimeField(
        auto_now_add=True,
        verbose_name='Создано',
        db_index=True,
    )

    # --------------------------------------------------------------------------
    # updated_at — когда запись была последний раз изменена
    # --------------------------------------------------------------------------
    # auto_now=True означает:
    #   - При КАЖДОМ save() Django автоматически обновляет поле
    #   - Нельзя задать вручную (Django перезапишет)
    #
    # Зачем это нужно:
    #   - Мягкое удаление: «если updated_at > 30 дней назад — корзина брошена»
    #   - Кэширование: «если updated_at не менялся — отдать из кэша»
    #   - Аудит: «когда изменили цену в последний раз»
    #
    # db_index НЕ ставим:
    #   updated_at редко используется в WHERE / ORDER BY.
    #   Каждый лишний индекс замедляет INSERT/UPDATE (PostgreSQL
    #   должен обновить все индексы при каждой записи).
    #   Для таблиц с частыми обновлениями (CartItem, Cart) лишние
    #   индексы — это минус к производительности.
    # --------------------------------------------------------------------------
    updated_at = models.DateTimeField(
        auto_now=True,
        verbose_name='Обновлено',
    )

    class Meta:
        # --------------------------------------------------------------------------
        # abstract = True — ключевой момент
        # --------------------------------------------------------------------------
        # Django НЕ создаёт таблицу для BaseModel. Вместо этого поля
        # created_at и updated_at «вклеиваются» в каждую дочернюю модель.
        #
        # Пример: class Cart(BaseModel) → таблица cart_cart будет содержать:
        #   id | created_at | updated_at | user_id | is_active | session_key_hash
        #
        # Если бы abstract = False (или не был указан):
        #   Django создал бы отдельную таблицу core_basemodel,
        #   а дочерние модели ссылались бы на неё через OneToOneField.
        #   Это Multi-table inheritance — нам он не нужен (лишние JOIN'ы).
        # --------------------------------------------------------------------------
        abstract = True

        # --------------------------------------------------------------------------
        # get_latest_by — для .latest() и .earliest()
        # --------------------------------------------------------------------------
        # Позволяет вызывать Model.objects.latest() без аргументов:
        #   Cart.objects.latest()  → самая новая корзина
        #
        # Без get_latest_by пришлось бы писать:
        #   Cart.objects.latest('created_at')
        #
        # Мелочь, но делает код чище.
        # --------------------------------------------------------------------------
        get_latest_by = ('created_at',)
